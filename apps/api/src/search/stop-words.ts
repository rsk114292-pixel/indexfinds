/**
 * 过滤停用词
 */
export function filterStopWords(tokens: string[]): string[] {
  return tokens.filter((token) => !ENGLISH_STOP_WORDS.has(token.toLowerCase()));
}

/**
 * 检查是否为停用词
 */
export function isStopWord(word: string): boolean {
  return ENGLISH_STOP_WORDS.has(word.toLowerCase());
}
